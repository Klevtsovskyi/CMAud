"""Квадратурні формули (переклад з MATLAB: i_*.m)."""
import numpy as np


def _vec(f, x):
    """Обчислення f у точках масиву x (f може бути скалярною)."""
    return np.array([f(t) for t in x], dtype=float)


def _lin_transform(a, b, X, C):
    """Лінійне перетворення з [-1,1] на [a,b]."""
    if a != -1 or b != 1:
        ab = 0.5 * (a + b)
        ba = 0.5 * (b - a)
        X = ab + ba * X
        C = ba * C
    return X, C


# ---------------------------------------------------------------- Чебишева
def i_cheb(a, b, f, n):
    """КФ Чебишева; n in [1,7] або n = 9."""
    if a > b:
        raise ValueError('I_CHEB: a>b')
    if n not in (1, 2, 3, 4, 5, 6, 7, 9):
        raise ValueError('I_CHEB: n має бути з [1,7] або n=9')

    X = np.zeros(n)
    C = 2.0 / n
    # вузли задаємо як невід'ємну половину, решта — симетрично
    half = {
        1: [],
        2: [0.5773502691],
        3: [0.7071067812],
        4: [0.7946544723, 0.1875924741],
        5: [0.8324974870, 0.3745414096],
        6: [0.8662468181, 0.4225186538, 0.2666354015],
        7: [0.8838617008, 0.5296567753, 0.3239118105],
        9: [0.9115893007, 0.6010186554, 0.5287617831, 0.1679061842],
    }[n]
    for i, v in enumerate(half):          # від найбільшого до найменшого
        X[n - 1 - i] = v
        X[i] = -v

    X, C = _lin_transform(a, b, X, C)
    return C * sum(f(x) for x in X)


# ------------------------------------------------- Центральні прямокутники
def i_crect(a, b, f, ep, mki):
    """Центральні прямокутники з уточненням сітки до точності ep."""
    A, B, z = (a, b, 1) if a <= b else (b, a, -1)
    k = 0
    h = B - A
    s = h * f(0.5 * (A + B))
    F = False
    while not F and k < mki:
        k += 1
        h *= 0.5
        x = A + 0.5 * h
        s1 = 0.0
        while x < B:
            s1 += f(x)
            x += h
        ss = h * s1
        F = abs(ss - s) / 3 < ep
        s = ss
    return z * s


def i_crectn(a, b, f, n):
    """Центральні прямокутники на рівномірній сітці з n точок."""
    A, B, z = (a, b, 1) if a <= b else (b, a, -1)
    if n < 0:
        n = -n
    elif n == 0:
        n = 21
    x = np.linspace(A, B, n)
    s = sum(f(0.5 * (x[k] + x[k + 1])) for k in range(n - 1))
    return z * (x[1] - x[0]) * s


# ------------------------------------------------------------------ Ерміта
def i_ermit(a, b, f, n):
    """КФ Ерміта (Чебишева 1-го роду) з вагою 1/sqrt(1-x^2)."""
    if a > b:
        raise ValueError('I_ERMIT: a>b')
    C = np.pi / n
    X = np.cos((np.arange(1, n + 1) - 0.5) * C)
    X, C = _lin_transform(a, b, X, C)
    return C * sum(f(x) for x in X)


# ------------------------------------------------------------------ Гаусса
def i_gauss(a, b, f, n):
    """КФ Гаусса, n in [1,7]."""
    if a > b:
        raise ValueError('I_GAUSS: a>b')
    if n < 1 or n > 7:
        raise ValueError('I_GAUSS: n має бути з [1,7]')

    X = np.zeros(n)
    C = np.ones(n)
    if n == 2:
        X[1] = 0.5773502691896258
        X[0] = -X[1]
        C = np.array([0.5, 0.5])
    elif n == 3:
        X[2] = 0.7745966692414834
        X[0] = -X[2]
        C = np.array([5, 8, 5]) / 18
    elif n == 4:
        X[3], X[2] = 0.8611363115940492, 0.3399810435848646
        X[0], X[1] = -X[3], -X[2]
        C[3] = C[0] = 0.1739274225687284
        C[2] = C[1] = 0.3260725774312716
    elif n == 5:
        X[4], X[3] = 0.9061798459386640, 0.5384693101056830
        X[0], X[1] = -X[4], -X[3]
        C[4] = C[0] = 0.1184634425280945
        C[3] = C[1] = 0.2393143352496832
        C[2] = 64 / 225
    elif n == 6:
        X[5], X[4], X[3] = 0.9324695142031520, 0.6612093864662644, 0.2386191860831970
        X[0], X[1], X[2] = -X[5], -X[4], -X[3]
        C[5] = C[0] = 0.0856622461895852
        C[4] = C[1] = 0.1803807865240693
        C[3] = C[2] = 0.2339569672863455
    elif n == 7:
        X[6], X[5], X[4] = 0.9491079123427596, 0.7415311855993944, 0.4058451513773970
        X[0], X[1], X[2] = -X[6], -X[5], -X[4]
        C[6] = C[0] = 0.0647424830844348
        C[5] = C[1] = 0.1398526957446384
        C[4] = C[2] = 0.1909150252525595
        C[3] = 256 / 1225
    C = 2 * C

    X, C = _lin_transform(a, b, X, C)
    return sum(C[i] * f(X[i]) for i in range(n))


# ------------------------------------------------------------------ Лагерра
def i_lager(f, n):
    """КФ Лагерра для int_0^inf exp(-x) f(x) dx, n in [1,5]."""
    tab = {
        1: ([1], [1]),
        2: ([0.585786, 3.414214], [0.853553, 0.146447]),
        3: ([0.415775, 2.29428, 6.289945],
            [0.711093, 0.278518, 0.0103893]),
        4: ([0.322548, 1.745761, 4.53662, 9.395071],
            [0.603154, 0.357419, 0.0388879, 0.000539295]),
        5: ([0.26356, 1.413403, 3.596426, 7.08581, 12.640801],
            [0.521756, 0.398667, 0.0759424, 0.00361176, 0.00002337]),
    }
    if n not in tab:
        raise ValueError('I_LAGER: n має бути з [1,5]')
    X, C = map(np.array, tab[n])
    return float(np.dot(C, _vec(f, X)))


# ------------------------------------------------------------------ Маркова
def i_markov(a, b, f, n):
    """КФ Маркова (Лобатто, вузли на кінцях), n in [2,10]."""
    if a > b:
        raise ValueError('I_MARKOV: a>b')
    if n < 2 or n > 10:
        raise ValueError('I_MARKOV: n має бути з [2,10]')

    # внутрішні вузли (невід'ємні, за спаданням) та ваги (від краю до центра)
    inner = {
        2: [], 3: [],
        4: [1 / np.sqrt(5)],
        5: [np.sqrt(3 / 7)],
        6: [0.76505532, 0.28523152],
        7: [0.83022390, 0.46884879],
        8: [0.87174015, 0.59170018, 0.20929922],
        9: [0.89975799541146, 0.67718627951074, 0.36311746382618],
        10: [0.91953391, 0.73877386, 0.47792495, 0.16527896],
    }[n]
    weights = {
        2: [1.0],
        3: [1 / 3, 4 / 3],
        4: [1 / 6, 5 / 6],
        5: [9 / 90, 49 / 90, 64 / 90],
        6: [0.06666667, 0.37847496, 0.55485837],
        7: [0.04761905, 0.27682605, 0.43174538, 0.48761905],
        8: [0.03571429, 0.21070423, 0.34112268, 0.41245881],
        9: [0.02777778, 0.16549536, 0.27453872, 0.34642851, 0.37151927],
        10: [0.02222222, 0.13330599, 0.22488934, 0.29204268, 0.32753976],
    }[n]

    pos = [1.0] + inner                          # додатні вузли (з краєм)
    X = np.zeros(n)
    C = np.zeros(n)
    for i, (xv, wv) in enumerate(zip(pos, weights)):
        X[n - 1 - i], X[i] = xv, -xv
        C[n - 1 - i] = C[i] = wv
    if n % 2 == 1:                               # центральний вузол
        X[n // 2] = 0.0
        C[n // 2] = weights[len(pos)]
    if n == 3:
        C = np.array([1, 4, 1]) / 3

    X, C = _lin_transform(a, b, X, C)
    return sum(C[i] * f(X[i]) for i in range(n))


# ------------------------------------------------------------------ Сімпсон
def i_simp(a, b, f, ep, mki):
    """Метод Сімпсона з уточненням сітки до точності ep."""
    A, B, z = (a, b, 1) if a <= b else (b, a, -1)
    k = 0
    h = 0.5 * (B - A)
    s1 = f(A) + f(B)
    s2 = 0.0
    s4 = f(0.5 * (B + A))
    s = h * (s1 + 4 * s4) / 3
    F = False
    while not F and k < mki:
        k += 1
        ho = h
        h *= 0.5
        s2 += s4
        s4 = 0.0
        x = A + h
        while x < B:
            s4 += f(x)
            x += ho
        ss = h * (s1 + 4 * s4 + 2 * s2) / 3
        F = abs(ss - s) / 15 < ep
        s = ss
    return z * s


def i_simpn(a, b, f, n):
    """Сімпсон на рівномірній сітці з n точок (n непарне)."""
    A, B, z = (a, b, 1) if a <= b else (b, a, -1)
    if n < 0:
        n = -n
    elif n == 0:
        n = 21
    if n < 3:
        n = 21
    x = np.linspace(A, B, n)
    s = (f(A) + f(B)
         + 4 * _vec(f, x[1:n - 1:2]).sum()
         + 2 * _vec(f, x[2:n - 2:2]).sum())
    return z * (x[1] - x[0]) / 3 * s


# ------------------------------------------------------------------ Трапеції
def i_trap(a, b, f, ep, mki):
    """Метод трапецій з уточненням сітки до точності ep."""
    A, B, z = (a, b, 1) if a <= b else (b, a, -1)
    k = 0
    h = B - A
    s0 = 0.5 * (f(A) + f(B))
    s1 = 0.0
    s = h * s0
    F = False
    while not F and k < mki:
        k += 1
        ho = h
        h *= 0.5
        x = A + h
        while x < B:
            s1 += f(x)
            x += ho
        ss = h * (s0 + s1)
        F = abs(ss - s) / 3 < ep
        s = ss
    return z * s


def i_trapn(a, b, f, n):
    """Трапеції на рівномірній сітці з n точок."""
    A, B, z = (a, b, 1) if a <= b else (b, a, -1)
    if n < 0:
        n = -n
    elif n == 0:
        n = 21
    x = np.linspace(A, B, n)
    s = 0.5 * (f(A) + f(B)) + _vec(f, x[1:n - 1]).sum()
    return z * (x[1] - x[0]) * s
