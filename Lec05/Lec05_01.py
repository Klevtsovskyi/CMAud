import numpy as np
import matplotlib.pyplot as plt

from scipy.interpolate import CubicSpline
from scipy.integrate import quad, simpson


# ============================================================
# Визначення функції
# ============================================================

def u(x):
    return np.sin(x)


# ============================================================
# Задання сплайнової сітки X
# ============================================================

n = 16
X = np.linspace(0, 6, n)


# Значення функції
U = u(X)


# ============================================================
# Кубічний сплайн
# ============================================================

S31 = CubicSpline(X, U)


# ============================================================
# Інтеграл кубічного сплайна
# ============================================================

In = S31.antiderivative()  # MATLAB:  In = ppint(S31)


# ============================================================
# Точне значення інтеграла
# ============================================================

# MATLAB:
# syms x
# f = sin(x)
# IR = int(f)
# Ir = subs(IR,x,6)-subs(IR,x,0)

# ∫ sin(x) dx = -cos(x)

Ir = -np.cos(6) + np.cos(0)

print(f"{'Точне значення=':<15} {Ir:18.10e}")


# ============================================================
# Інтеграл за допомогою сплайна
# ============================================================

I = In(6) - In(0)

print(
    f"{'Функція':<15}"
    f"{'Наближене значення':>18}"
    f"{'Похибка':>18}"
)

print(
    f"{'spline':<15}"
    f"{I:18.10e}"
    f"{I - Ir:18.10e}"
)


# ============================================================
# Метод трапецій
# ============================================================

S = np.trapezoid(U, X)

print(
    f"{'trapz(X,U)':<15}"
    f"{S:18.10e}"
    f"{S - Ir:18.10e}"
)


# ============================================================
# Метод Сімпсона
# ============================================================

S = simpson(U, x=X)

print(
    f"{'simpson(X,U)':<15}"
    f"{S:18.10e}"
    f"{S - Ir:18.10e}"
)


# ============================================================
# Квадратура scipy.integrate.quad
# ============================================================

S, error = quad(u, 0, 6)

print(
    f"{'quad(u,0,6)':<15}"
    f"{S:18.10e}"
    f"{S - Ir:18.10e}"
)


# ============================================================
# Сітка інтерполяції
# ============================================================

N = 10 * n + 1

XX = np.linspace(0, 6, N)


# ============================================================
# Графічне порівняння
# ============================================================

plt.figure(figsize=(12, 5))

# Інтеграл сплайна
Y = In(XX)


# ============================================================
# Точний інтеграл для кожної точки
# ============================================================

# ∫ sin(x) dx = -cos(x)
U_exact = -np.cos(XX)


# ============================================================
# Вирівнювання початкової точки
# ============================================================

C = Y[0] - U_exact[0]

Y = Y - C


# ============================================================
# Графік
# ============================================================

plt.subplot(1, 2, 1)

plt.plot(
    XX,
    U_exact,
    "k:",
    label="Точний інтеграл"
)

plt.plot(
    XX,
    Y,
    "b",
    label="Інтеграл сплайна"
)

plt.grid()
plt.xlabel("x")
plt.ylabel("int(u)")
plt.title("Невизначений інтеграл")

plt.legend()


# ============================================================
# Похибка
# ============================================================

R = Y - U_exact

r = np.max(np.abs(R))

print()
print(f"||In - int(u)||∞ = {r:.10f}")


plt.subplot(1, 2, 2)

plt.plot(XX, R)

plt.grid()
plt.xlabel("x")
plt.ylabel("R(x)")
plt.title("Похибка R(X) для int(u)")


plt.tight_layout()
plt.show()
